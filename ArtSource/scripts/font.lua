-- Pixel font for Disaster Safety.
-- Each glyph is a list of rows. Cell layout (11 rows):
--   rows 1-2  accent space (used by capital N-tilde only)
--   rows 3-9  cap height (7 rows); baseline is the bottom of row 9
--   rows 10-11 descenders (g, j, p, q, y, comma)
-- Glyphs below are written as 7 body rows plus optional descender rows
-- and optional accent rows, and are normalised to 11 rows by F.cell().

