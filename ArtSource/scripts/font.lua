F.glyphs = G

-- Returns an 11-row array of strings for a glyph.
function F.cell(ch)
  local g = G[ch] or G["?"]
  local w = #g.body[1]
  local blank = string.rep(".", w)
  local rows = {}
  rows[1] = g.accent[1] or blank
  rows[2] = g.accent[2] or blank
  for i = 1, 7 do rows[2 + i] = g.body[i] end
  rows[10] = g.desc[1] or blank
  rows[11] = g.desc[2] or blank
  return rows, w
end

-- Iterate UTF-8 characters of a string.
function F.chars(s)
  local out = {}
  for _, cp in utf8.codes(s) do out[#out + 1] = utf8.char(cp) end
  return out
end

function F.width(s, scale)
  scale = scale or 1
  local w = 0
  local cs = F.chars(s)
  for i, ch in ipairs(cs) do
    local _, gw = F.cell(ch)
    w = w + gw
    if i < #cs then w = w + 1 end
  end
  return w * scale
end

-- Draw text with its cap top at (x, y). plot(px, py, glyphRow) is called
-- for every set pixel; glyphRow is the 1-based body row (1..7, 8..9 for
-- descenders, 0/-1 for accents) so callers can shade by row.
function F.draw(s, x, y, scale, plot)
  scale = scale or 1
  local cx = x
  for _, ch in ipairs(F.chars(s)) do
    local rows, w = F.cell(ch)
    for r = 1, 11 do
      local row = rows[r]
      for c = 1, #row do
        if row:sub(c, c) == "#" then
          local gx = cx + (c - 1) * scale
          local gy = y + (r - 3) * scale
          for sy = 0, scale - 1 do
            for sx = 0, scale - 1 do plot(gx + sx, gy + sy, r - 2) end
          end
        end
      end
    end
    cx = cx + (w + 1) * scale
  end
end

-- Ordered list of every glyph, for building the font atlas.
function F.all()
  local list = {}
  for ch, _ in pairs(G) do list[#list + 1] = ch end
  table.sort(list, function(a, b) return utf8.codepoint(a) < utf8.codepoint(b) end)
  return list
end

return F
